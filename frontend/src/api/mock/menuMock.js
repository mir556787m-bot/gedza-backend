const BADGES = ['ХИТ', 'НОВИНКА', 'ОСТРО'];

export function menuMock() {
  const items = [];
  let id = 1;

  CATEGORIES.forEach((cat, catIdx) => {
    const names = NAMES_BY_CATEGORY[cat] || [];
    names.forEach((name, i) => {
      const price = 100 + ((catIdx * 50) + (i * 30)) % 2000;
      const mass = `${150 + (id % 5) * 50} г`;
      const badge = BADGES[(catIdx + i) % 5 === 0 ? 0 : -1] || null;
      items.push({
        id,
        plateID: 10000 + id,
        name,
        price,
        mass,
        category: cat,
        badge: badge && (catIdx + i) % 3 === 0 ? badge : null,
        image: `https://placehold.co/400x400/d40000/ffffff?text=${encodeURIComponent(name)}`,
        description: `${name}. Свежие ингредиенты, приготовлено с любовью.\nПодаётся с соевым соусом и имбирём.`,
      });
      id++;
    });
  });

  return items;
}